/**
 * The practice fixture (`fixtures/practice-schedule-2026/`) as the pgTAP file of the practice import reads it
 * (`supabase/tests/_practice_import_fixture.sql`, PR 10, task K2): the league (divisions with their stored practice
 * settings, teams, coaches and their team assignments, locations, fields and halves), the 710 rows of the schedule as
 * core stages them (`parsePracticeRows`, then `toStagedPracticeRow`), and the mapping an admin confirms by accepting
 * every proposal the mapping step shows (the exact names and the alias file's spellings; `acceptAllProposals`).
 *
 * The SQL file is GENERATED from this module and checked in; `tests/mockPracticeImport.test.js` requires the file to be
 * what this module builds now (a changed fixture or a changed core is a changed file), and rewrites it when
 * `WRITE_PRACTICE_PGTAP=1`. The ids are uuids made from the fixture's own names (md5), so they are stable, and they
 * mean nothing to the product. Every name is the fixture's placeholder; coaches get an `example.com` address.
 */

import { createHash } from 'node:crypto';
import {
  parsePracticeRows,
  proposePracticeMapping,
  readPracticeAliases,
  toStagedPracticeRow,
} from '../../packages/core/src/practiceImport/index.js';
import { acceptAllProposals, loadPracticeFixture } from './practiceFixtureLoad.js';

export const PRACTICE_PGTAP_ORG = 'a1111111-1111-1111-1111-111111111111';
export const PRACTICE_PGTAP_SEASON = 'a1111111-1111-1111-1111-111111111aaa';

/** A stable uuid for a fixture name: the md5 of it, shaped as a uuid (version nibble 4, variant 8). */
export function fixtureUuid(name) {
  const h = createHash('md5').update(`practice-import-pgtap:${name}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

/** The fixture, parsed, staged and mapped, with every league id a uuid. */
export function practicePgtapWorld() {
  const fx = loadPracticeFixture();
  const parsed = parsePracticeRows({
    headers: fx.schedule.headers,
    rows: fx.schedule.rows,
    season: fx.season,
  });
  const { aliases } = readPracticeAliases({
    headers: fx.aliases.headers,
    rows: fx.aliases.rows,
    league: fx.league,
  });
  const decisions = acceptAllProposals((d) =>
    proposePracticeMapping({ rows: parsed.rows, league: fx.league, aliases, decisions: d })
  );
  /** @param {string} id a league id such as `div:U05 Boys` */
  const u = (id) => fixtureUuid(id);
  // What is STORED is the effective decision of every label (an exact single match is stored as a `map` with source
  // `exact`), as the games import stores its mapping: the SQL reads only stored decisions and guesses nothing.
  const entries = proposePracticeMapping({
    rows: parsed.rows,
    league: fx.league,
    aliases,
    decisions,
  });
  /** @type {Record<string, Record<string, any>>} */
  const mapping = {};
  for (const [group, list] of Object.entries(entries)) {
    mapping[group] = {};
    for (const entry of list) {
      const d = entry.effective;
      if (!d) continue;
      mapping[group][entry.key] =
        d.action === 'map' ? { action: 'map', id: u(d.id), source: d.source ?? 'exact' } : { ...d };
    }
  }
  const coaches = new Map();
  /** @type {Array<{ team: string, coach: string, role: string }>} */
  const coachOf = [];
  for (const t of fx.teams.rows) {
    ['Coach 1', 'Coach 2', 'Coach 3'].forEach((col, i) => {
      const name = (t[col] ?? '').trim();
      if (!name) return;
      if (!coaches.has(name)) coaches.set(name, u(`coach:${name}`));
      coachOf.push({
        team: u(`team:${t.Team}`),
        coach: coaches.get(name),
        role: i === 0 ? 'lead' : 'assistant',
      });
    });
  }
  return {
    fixture: fx,
    parsed,
    staged: parsed.rows.map((r) => toStagedPracticeRow(/** @type {any} */ (r))),
    mapping,
    league: {
      divisions: fx.league.divisions.map((d) => ({ ...d, id: u(d.id) })),
      teams: fx.league.teams.map((t) => ({ ...t, id: u(t.id), divisionId: u(t.divisionId) })),
      locations: fx.league.locations.map((l) => ({ ...l, id: u(l.id) })),
      fields: fx.league.fields.map((f) => ({ ...f, id: u(f.id), locationId: u(f.locationId) })),
      subunits: fx.league.subunits.map((s) => ({ ...s, id: u(s.id), fieldId: u(s.fieldId) })),
      coaches: [...coaches].map(([name, id]) => ({ id, name })),
      coachOf,
    },
    season: fx.season,
  };
}

/** @param {unknown} v */
const lit = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

/** The SQL include, as checked in. */
export function buildPracticeImportPgtapSql() {
  const w = practicePgtapWorld();
  const org = lit(PRACTICE_PGTAP_ORG);
  const season = lit(PRACTICE_PGTAP_SEASON);
  const L = w.league;
  const lines = [];
  lines.push(
    '-- GENERATED by tests/helpers/practiceImportPgtapFixture.js from fixtures/practice-schedule-2026/ (PR 10). Do not edit:',
    '-- WRITE_PRACTICE_PGTAP=1 npx vitest run tests/mockPracticeImport.test.js rewrites it, and that test fails while it differs.',
    '-- Included by supabase/tests/practice_import_apply_rollback.sql; run alone it passes one assertion and does nothing else.',
    "-- Every name is the fixture's placeholder (AGENTS.md section 2); every id is an md5 of that name.",
    '\\if :{?squadlogic_practice_fixture_include}',
    '\\else',
    'BEGIN;',
    'SELECT plan(1);',
    "SELECT pass('practice import fixture helper is available; include it with \\ir _practice_import_fixture.sql');",
    'SELECT * FROM finish();',
    'ROLLBACK;',
    '\\quit',
    '\\endif',
    '',
    `UPDATE public.season_settings SET season_start = ${lit(w.season.startDate)}, season_end = ${lit(w.season.endDate)} WHERE id = ${season};`,
    'INSERT INTO public.divisions (id, organization_id, season_settings_id, name, practices_per_week, practice_minutes) VALUES'
  );
  lines.push(
    L.divisions
      .map(
        (d) =>
          `    (${lit(d.id)}, ${org}, ${season}, ${lit(d.name)}, ${d.practicesPerWeek}, ${d.practiceMinutes})`
      )
      .join(',\n') + ';'
  );
  lines.push('INSERT INTO public.teams (id, organization_id, division_id, name) VALUES');
  lines.push(
    L.teams
      .map((t) => `    (${lit(t.id)}, ${org}, ${lit(t.divisionId)}, ${lit(t.name)})`)
      .join(',\n') + ';'
  );
  lines.push(
    'INSERT INTO public.coaches (id, organization_id, season_settings_id, full_name, email, status) VALUES'
  );
  lines.push(
    L.coaches
      .map(
        (c, i) =>
          `    (${lit(c.id)}, ${org}, ${season}, ${lit(c.name)}, ${lit(`coach${i + 1}@example.com`)}, 'active')`
      )
      .join(',\n') + ';'
  );
  lines.push(
    'INSERT INTO public.team_coach_assignments (organization_id, team_id, coach_id, role, effective_from, started_via) VALUES'
  );
  lines.push(
    L.coachOf
      .map(
        (a) =>
          `    (${org}, ${lit(a.team)}, ${lit(a.coach)}, ${lit(a.role)}, ${lit(w.season.startDate)}, 'admin')`
      )
      .join(',\n') + ';'
  );
  lines.push('INSERT INTO public.locations (id, organization_id, name) VALUES');
  lines.push(
    L.locations.map((l) => `    (${lit(l.id)}, ${org}, ${lit(l.name)})`).join(',\n') + ';'
  );
  lines.push(
    'INSERT INTO public.fields (id, organization_id, location_id, name, supports_halves) VALUES'
  );
  lines.push(
    L.fields
      .map((f) => `    (${lit(f.id)}, ${org}, ${lit(f.locationId)}, ${lit(f.name)}, true)`)
      .join(',\n') + ';'
  );
  lines.push('INSERT INTO public.field_subunits (id, organization_id, field_id, label) VALUES');
  lines.push(
    L.subunits
      .map((s) => `    (${lit(s.id)}, ${org}, ${lit(s.fieldId)}, ${lit(s.name)})`)
      .join(',\n') + ';'
  );
  lines.push('');
  lines.push(
    '-- The 710 rows of practice-schedule.csv as core stages them, one JSON object a line, for a job.'
  );
  lines.push(
    'CREATE FUNCTION pg_temp.stage_fixture(p_job uuid) RETURNS integer LANGUAGE plpgsql AS $f$'
  );
  lines.push('DECLARE n integer;');
  lines.push('BEGIN');
  lines.push(
    '    INSERT INTO public.staging_import_rows (organization_id, import_job_id, import_type, source_row_number, raw_payload, normalized_payload, validation_errors)'
  );
  lines.push(
    `    SELECT ${org}, p_job, 'practice_schedule', (e ->> 'n')::int, '{}'::jsonb, e -> 'p', COALESCE(e -> 'v', '[]'::jsonb)`
  );
  lines.push('      FROM jsonb_array_elements($j$[');
  lines.push(
    w.staged
      .map((s) =>
        JSON.stringify({
          n: s.source_row_number,
          p: s.normalized_payload,
          ...(s.validation_errors.length ? { v: s.validation_errors } : {}),
        })
      )
      .join(',\n')
  );
  lines.push(']$j$::jsonb) e;');
  lines.push('    GET DIAGNOSTICS n = ROW_COUNT;');
  lines.push('    RETURN n;');
  lines.push('END');
  lines.push('$f$;');
  lines.push(
    '-- The mapping an admin confirms by accepting every proposal (exact names and the alias file).'
  );
  lines.push(
    'CREATE FUNCTION pg_temp.fixture_mapping() RETURNS jsonb LANGUAGE sql IMMUTABLE AS $f$ SELECT $j$'
  );
  lines.push(JSON.stringify(w.mapping));
  lines.push('$j$::jsonb $f$;');
  lines.push(
    'GRANT EXECUTE ON FUNCTION pg_temp.stage_fixture(uuid), pg_temp.fixture_mapping() TO PUBLIC;'
  );
  return `${lines.join('\n')}\n`;
}
